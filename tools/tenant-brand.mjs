// Tenant brand onboarding: one seed color in, a validated brand ramp out.
// Usage: node tools/tenant-brand.mjs "#0EA5E9" "azure"
// Writes: outputs/tenants/<name>/sis-<name>-palette.tokens.json (DTCG)
//         outputs/tenants/<name>/tokens-studio-legacy.json (Figma import)
//         and prints a WCAG contrast table for the generated ramp.
import { readFile, writeFile, mkdir } from "node:fs/promises";

const [seedRaw, nameRaw] = process.argv.slice(2);
const seed = (seedRaw || "").trim();
const name = (nameRaw || "tenant").toLowerCase().replace(/[^a-z0-9-]/g, "-");
if (!/^#[0-9a-fA-F]{6}$/.test(seed)) {
  console.error("Usage: node tools/tenant-brand.mjs \"#RRGGBB\" \"tenant-name\"");
  process.exit(1);
}

// --- HSL ramp generation around the seed hue ---
const hexToHsl = (hex) => {
  const r = parseInt(hex.slice(1, 3), 16) / 255;
  const g = parseInt(hex.slice(3, 5), 16) / 255;
  const b = parseInt(hex.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h /= 6;
  }
  return [h * 360, s * 100, l * 100];
};
const hslToHex = (h, s, l) => {
  const a = s / 100 * Math.min(l / 100, 1 - l / 100);
  const f = (n) => {
    const k = (n + h / 30) % 12;
    const c = l / 100 - a * Math.max(-1, Math.min(k - 3, Math.min(9 - k, 1)));
    return Math.round(255 * c).toString(16).padStart(2, "0");
  };
  return `#${f(0)}${f(8)}${f(4)}`.toUpperCase();
};

const [h0, s0, l0] = hexToHsl(seed);
// Eleven ramp steps: 50..950. The seed sits at 500 unless it is very light or dark.
const scale = [[50, 97], [100, 94], [200, 87], [300, 78], [400, 66], [500, Math.min(58, Math.max(38, l0))], [600, Math.max(30, Math.min(50, l0 - 10))], [700, 38], [800, 30], [900, 24], [950, 16]];
const ramp = {};
for (const [step, l] of scale) {
  ramp[String(step)] = hslToHex(h0, Math.max(42, s0), l);
}

// --- WCAG contrast validation against white text (the action-on-primary case) ---
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const checks = [];
for (const step of [500, 600, 700, 800]) {
  const ratio = contrast(ramp[step], "#FFFFFF");
  checks.push({ step, ratio: ratio.toFixed(2), passesAA: ratio >= 4.5 });
}

// --- Emit DTCG + Tokens Studio legacy files ---
const dtcg = {
  "$description": `SIS ${name} tenant brand ramp. Seed ${seed}. Generated by tools/tenant-brand.mjs.`,
  ref: { color: { brand: Object.fromEntries(Object.entries(ramp).map(([step, value]) => [step, { "$type": "color", "$value": value }])) } },
};
const legacy = {
  ...Object.fromEntries(Object.entries(ramp).map(([step, value]) => [`ref.color.brand.${step}`, { value, type: "color" }])),
  "sys.color.light.action-primary-bg": { value: "{ref.color.brand.600}", type: "color" },
  "sys.color.dark.action-primary-bg": { value: "{ref.color.brand.500}", type: "color" },
};

const dir = `outputs/tenants/${name}`;
await mkdir(dir, { recursive: true });
await writeFile(`${dir}/sis-${name}-palette.tokens.json`, JSON.stringify(dtcg, null, 2) + "\n");
await writeFile(`${dir}/tokens-studio-legacy.json`, JSON.stringify(legacy, null, 2) + "\n");

console.log(`Tenant "${name}" from seed ${seed}`);
console.log("Ramp:", JSON.stringify(ramp));
console.log("White-text contrast on action candidates:");
for (const c of checks) console.log(`  ${c.step}: ${c.ratio}:1 ${c.passesAA ? "AA pass" : "AA FAIL"}`);
const best = checks.find((c) => c.passesAA);
console.log(`Recommended action-primary: brand ${best ? best.step : 700} (first AA pass on white)`);
console.log(`Files: ${dir}/sis-${name}-palette.tokens.json, ${dir}/tokens-studio-legacy.json`);

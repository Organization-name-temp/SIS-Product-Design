// Generates native mobile token files from the canonical DTCG sources.
// Usage: node outputs/mobile/generate.mjs
// Writes: outputs/mobile/ios/SISTokens.swift, outputs/mobile/android/sis_tokens.xml
import { readFile, writeFile, mkdir } from "node:fs/promises";

const root = new URL("../../", import.meta.url).pathname;
const read = async (f) => JSON.parse(await readFile(root + f, "utf8"));

const palette = await read("foundations/sis-ejust-palette.tokens.json");
const spacing = await read("foundations/sis-spacing.tokens.json");
const radius = await read("foundations/sis-radius.tokens.json");

const hex = (v) => v["$value"] ?? v;
const alias = (v) => (typeof v === "string" && v.startsWith("{") ? v.slice(1, -1) : null);

// ---- iOS: Swift enum with static UIColor/CGFloat constants ----
const swiftColors = [];
const swiftFloats = [];
for (const [family, steps] of Object.entries(palette.ref.color)) {
  for (const [step, token] of Object.entries(steps)) {
    const name = `ref${family}${step}`.replace(/-/g, "");
    swiftColors.push(`    static let ${name} = UIColor(hex: 0x${hex(token).slice(1)})`);
  }
}
for (const [theme, roles] of Object.entries(palette.sys.color)) {
  for (const [role, token] of Object.entries(roles)) {
    const a = alias(token.$value);
    if (!a) continue;
    const parts = a.split("."); // ref.color.<fam>.<step>
    const name = `${theme}${role.replace(/-/g, "_")}`;
    swiftColors.push(`    static let sys_${name} = SIS.ref${parts[2]}${parts[3]}`.replace(/-/g, ""));
  }
}
for (const [name, token] of Object.entries(spacing.ref.space)) {
  swiftFloats.push(`    static let space${name} = CGFloat(${parseFloat(token.$value) * 16})`);
}
for (const [name, token] of Object.entries(radius.sys.radius)) {
  const v = String(token.$value);
  if (!v.includes("%")) swiftFloats.push(`    static let radius${name.replace(/-/g, "_")} = CGFloat(${parseFloat(v)})`);
}

const swift = `// Generated by outputs/mobile/generate.mjs from the canonical SIS tokens. Do not edit.
import UIKit

public enum SISTokens {
${swiftColors.join("\n")}
${swiftFloats.join("\n")}
}

extension UIColor {
    convenience init(hex: UInt32) {
        self.init(
            red: CGFloat((hex >> 16) & 0xFF) / 255,
            green: CGFloat((hex >> 8) & 0xFF) / 255,
            blue: CGFloat(hex & 0xFF) / 255,
            alpha: 1
        )
    }
}
`;

// ---- Android: XML resources ----
const androidColors = [];
for (const [family, steps] of Object.entries(palette.ref.color)) {
  for (const [step, token] of Object.entries(steps)) {
    androidColors.push(`    <color name="ref_color_${family}_${step}">${hex(token)}</color>`);
  }
}
for (const [theme, roles] of Object.entries(palette.sys.color)) {
  for (const [role, token] of Object.entries(roles)) {
    const a = alias(token.$value);
    if (!a) continue;
    const parts = a.split(".");
    androidColors.push(`    <color name="sys_color_${theme}_${role}">@color/ref_color_${parts[2]}_${parts[3]}</color>`);
  }
}
const androidDims = [];
for (const [name, token] of Object.entries(spacing.ref.space)) {
  androidDims.push(`    <dimen name="space_${name}">${parseFloat(token.$value) * 16}dp</dimen>`);
}
for (const [name, token] of Object.entries(radius.sys.radius)) {
  const v = String(token.$value);
  if (!v.includes("%")) androidDims.push(`    <dimen name="radius_${name}">${parseFloat(v)}dp</dimen>`);
}

const android = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by outputs/mobile/generate.mjs from the canonical SIS tokens. Do not edit. -->
<resources>
    <color name="ref_color_brand_500">#CD1722</color>
${androidColors.join("\n")}
${androidDims.join("\n")}
</resources>
`;

await mkdir(root + "outputs/mobile/ios", { recursive: true });
await mkdir(root + "outputs/mobile/android", { recursive: true });
await writeFile(root + "outputs/mobile/ios/SISTokens.swift", swift);
await writeFile(root + "outputs/mobile/android/sis_tokens.xml", android);
console.log("mobile tokens written: SISTokens.swift, sis_tokens.xml");
